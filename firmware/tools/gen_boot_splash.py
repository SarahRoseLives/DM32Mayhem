"""Render a board's boot splash source image into the C file the firmware embeds (run by hand).

    gen_boot_splash.py --input boot_splash.jpg --output boards/dm32/boot_splash.c \
        --name dm32_boot_splash --width 240 --height 320 [--palette BOOT_SPLASH_PALETTE] [--preview out.png]

The image is scaled to fit the panel without cropping (letterboxed on a background sampled from its own edges) and
quantized to the 16 colors a bpp 4 frame buffer holds, dithered. The output is a 4 bpp palette image: two pixels a
byte, high nibble left, plus the 16 RGB565 colors, as a hal_image_t. It is deterministic: the same input gives the
same bytes, so the generated file is committed and the build needs no Pillow. Run it again after changing the source
image.
"""
import argparse
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("gen_boot_splash.py needs Pillow (pip install Pillow)")


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def edge_color(img):
    """The average of the leftmost and rightmost columns, so letterbox bars blend into the picture."""
    w, h = img.size
    px = img.load()
    r = g = b = n = 0
    for y in range(h):
        for x in (0, w - 1):
            pr, pg, pb = px[x, y][:3]
            r += pr
            g += pg
            b += pb
            n += 1
    return (r // n, g // n, b // n)


def render(path, width, height):
    src = Image.open(path).convert("RGB")
    sw, sh = src.size
    scale = min(width / sw, height / sh)
    nw, nh = max(1, round(sw * scale)), max(1, round(sh * scale))
    art = src.resize((nw, nh), Image.LANCZOS)
    canvas = Image.new("RGB", (width, height), edge_color(art))
    canvas.paste(art, ((width - nw) // 2, (height - nh) // 2))
    # tobytes() of a P image is one palette index a pixel. Octree covers the small, saturated accents (the wordmark
    # and the radio's screen) that median cut, splitting by population, folds into the dark background
    return canvas.quantize(colors=16, method=Image.FASTOCTREE, dither=Image.FLOYDSTEINBERG)


def packed(q):
    w, h = q.size
    idx = q.tobytes()
    out = bytearray()
    for y in range(h):
        row = idx[y * w:(y + 1) * w]
        for x in range(0, w, 2):
            hi = row[x]
            lo = row[x + 1] if x + 1 < w else 0
            out.append((hi << 4) | lo)
    return bytes(out)


def emit(args, q):
    pal = q.getpalette()[:48]
    colors = [rgb565(*pal[i * 3:i * 3 + 3]) for i in range(16)]
    bits = packed(q)
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 The RadioFoundry Authors",
        "// Generated by tools/gen_boot_splash.py from %s; do not edit. Regenerate after changing the image." %
        args.input,
        '#include "board.h"',
        "",
        "#define %s_W %du" % (args.palette, q.size[0]),
        "#define %s_H %du" % (args.palette, q.size[1]),
        "",
        "static const uint16_t %s[16] = {" % args.palette,
    ]
    for i in range(0, 16, 8):
        lines.append("\t" + " ".join("0x%04X," % c for c in colors[i:i + 8]))
    lines += [
        "};",
        "",
        "static const uint8_t %s_BITS[%d] = {" % (args.palette, len(bits)),
    ]
    for i in range(0, len(bits), 16):
        lines.append("\t" + " ".join("0x%02X," % b for b in bits[i:i + 16]))
    lines += [
        "};",
        "",
        "const hal_image_t %s = {" % args.name,
        "\t.width = %s_W," % args.palette,
        "\t.height = %s_H," % args.palette,
        "\t.palette = %s," % args.palette,
        "\t.bits = %s_BITS," % args.palette,
        "};",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--name", required=True, help="the hal_image_t symbol")
    ap.add_argument("--palette", help="prefix for the palette and bits arrays (default: <name>_DATA)")
    ap.add_argument("--width", type=int, default=240)
    ap.add_argument("--height", type=int, default=320)
    ap.add_argument("--preview", help="also write the quantized image as a PNG")
    args = ap.parse_args()
    if args.palette is None:
        args.palette = args.name.upper() + "_DATA"
    q = render(args.input, args.width, args.height)
    if args.preview:
        q.convert("RGB").save(args.preview)
    text = emit(args, q)
    try:
        with open(args.output, encoding="utf-8") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
